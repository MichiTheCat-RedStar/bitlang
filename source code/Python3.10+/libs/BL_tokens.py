BIT_CALCS = {
	'число':[str(x) for x in range(10)], # 0..9
	'алгебраическое':['/', '%', '*', '+', '-', '='], # math
	'логическое':['!', '<', '>', '|', '&'], # logic (символ должен быть один)
	'переменная':[x for x in list(ascii_letters+'_')] # a-zA-Z_
}
